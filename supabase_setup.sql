    select 1 from pg_publication_tables 
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'precios'
  ) then
    alter publication supabase_realtime add table public.precios;
  end if;

  if not exists (
    select 1 from pg_publication_tables 
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'comercios'
  ) then
    alter publication supabase_realtime add table public.comercios;
  end if;
end
$$;

