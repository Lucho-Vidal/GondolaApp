-- 1. Creación de la tabla principal de precios
create table if not exists public.precios (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  codigo_barra varchar(64),
  comercio varchar(80) not null,
  producto varchar(150) not null,
  precio_total numeric(12,2) not null check (precio_total > 0),
  cantidad numeric(8,3) not null default 1.0 check (cantidad > 0),
  unidad varchar(10) not null check (unidad in ('kg', 'g', 'l', 'ml', 'un')),
  precio_unitario numeric(12,2) not null check (precio_unitario > 0),
  user_id uuid default auth.uid() references auth.users(id) on delete set null
);

-- Asegurar columna user_id en caso de que la tabla ya exista
alter table public.precios
  add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete set null;

-- Índices para optimización de consultas
create index if not exists idx_precios_codigo_barra on public.precios (codigo_barra);
create index if not exists idx_precios_producto on public.precios (lower(producto));
create index if not exists idx_precios_comercio on public.precios (lower(comercio));
create index if not exists idx_precios_precio_unitario on public.precios (precio_unitario asc);
create index if not exists idx_precios_created_at on public.precios (created_at desc);
create index if not exists idx_precios_user_id on public.precios (user_id);

-- Activar RLS en precios
alter table public.precios enable row level security;

-- Limpieza de políticas previas de precios
drop policy if exists "Permitir lectura anonima de precios" on public.precios;
drop policy if exists "Permitir insercion anonima de precios" on public.precios;
drop policy if exists "Permitir eliminacion anonima de precios" on public.precios;
drop policy if exists "Permitir actualizacion anonima de precios" on public.precios;
drop policy if exists "Lectura publica de precios" on public.precios;
drop policy if exists "Insercion segura de precios" on public.precios;
drop policy if exists "Insercion solo usuarios autenticados" on public.precios;
drop policy if exists "Edicion de precios propios" on public.precios;
drop policy if exists "Eliminacion de precios propios" on public.precios;

-- POLÍTICAS SEGURAS PARA PRECIOS:
-- (A) Lectura pública: cualquier visitante puede consultar y comparar precios
create policy "Lectura publica de precios"
  on public.precios for select
  to anon, authenticated
  using (true);

-- (B) Inserción: SOLO usuarios autenticados (Google, Facebook, etc.) pueden subir precios
create policy "Insercion solo usuarios autenticados"
  on public.precios for insert
  to authenticated
  with check (
    precio_total > 0 and 
    cantidad > 0 and
    length(producto) between 2 and 150 and
    length(comercio) between 2 and 80 and
    (user_id is null or user_id = auth.uid())
  );

-- (C) Edición: SOLO el usuario autenticado que cargó el precio puede modificarlo
create policy "Edicion de precios propios"
  on public.precios for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- (D) Eliminación: SOLO el usuario autenticado que cargó el precio puede borrarlo
create policy "Eliminacion de precios propios"
  on public.precios for delete
  to authenticated
  using (auth.uid() = user_id);


-- ============================================================================
-- 2. Creación y Seguridad de la tabla de comercios
-- ============================================================================
create table if not exists public.comercios (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  nombre varchar(80) not null unique,
  ubicacion varchar(150),
  descripcion text,
  user_id uuid default auth.uid() references auth.users(id) on delete set null
);

-- Asegurar columna user_id en comercios si ya existía
alter table public.comercios
  add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete set null;

-- Índices para comercios
create index if not exists idx_comercios_nombre on public.comercios (lower(nombre));

-- Activar RLS en comercios
alter table public.comercios enable row level security;

-- Limpieza de políticas previas de comercios
drop policy if exists "Permitir lectura anonima de comercios" on public.comercios;
drop policy if exists "Permitir insercion anonima de comercios" on public.comercios;
drop policy if exists "Permitir actualizacion anonima de comercios" on public.comercios;
drop policy if exists "Permitir eliminacion anonima de comercios" on public.comercios;
drop policy if exists "Lectura publica de comercios" on public.comercios;
drop policy if exists "Insercion de comercios" on public.comercios;
drop policy if exists "Insercion de comercios autenticados" on public.comercios;
drop policy if exists "Edicion de comercios propios" on public.comercios;
drop policy if exists "Eliminacion de comercios propios" on public.comercios;

-- POLÍTICAS SEGURAS PARA COMERCIOS:
-- (A) Lectura pública de supermercados/comercios
create policy "Lectura publica de comercios"
  on public.comercios for select
  to anon, authenticated
  using (true);

-- (B) Inserción: solo usuarios autenticados pueden registrar nuevos comercios
create policy "Insercion de comercios autenticados"
  on public.comercios for insert
  to authenticated
  with check (
    length(nombre) between 2 and 80 and
    (user_id is null or user_id = auth.uid())
  );

-- (C) Edición: Solo quien creó un comercio personalizado puede editarlo (los base tienen user_id null)
create policy "Edicion de comercios propios"
  on public.comercios for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- (D) Eliminación: Solo quien creó un comercio personalizado puede eliminarlo
create policy "Eliminacion de comercios propios"
  on public.comercios for delete
  to authenticated
  using (auth.uid() = user_id);


