-- ============================================================================
-- ChangoCheck — Configuración de Base de Datos Supabase (T-01 & Comercios)
-- ============================================================================

-- 1. Creación de la tabla principal de precios
create table if not exists public.precios (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  codigo_barra varchar(64),
  comercio varchar(80) not null,
  producto varchar(150) not null,
  precio_total numeric(12,2) not null check (precio_total > 0),
  cantidad numeric(8,3) not null default 1.0 check (cantidad > 0),
  unidad varchar(10) not null check (unidad in ('kg', 'g', 'l', 'ml', 'un')),
  precio_unitario numeric(12,2) not null check (precio_unitario > 0)
);

-- Índices para precios
create index if not exists idx_precios_codigo_barra on public.precios (codigo_barra);
create index if not exists idx_precios_producto on public.precios (lower(producto));
create index if not exists idx_precios_comercio on public.precios (lower(comercio));
create index if not exists idx_precios_precio_unitario on public.precios (precio_unitario asc);
create index if not exists idx_precios_created_at on public.precios (created_at desc);

-- RLS y Políticas para precios
alter table public.precios enable row level security;

create policy "Permitir lectura anonima de precios"
  on public.precios for select to anon using (true);

create policy "Permitir insercion anonima de precios"
  on public.precios for insert to anon with check (true);

create policy "Permitir eliminacion anonima de precios"
  on public.precios for delete to anon using (true);

create policy "Permitir actualizacion anonima de precios"
  on public.precios for update to anon using (true);


-- ============================================================================
-- 2. Creación de la tabla de comercios (nombre, ubicación, descripción)
-- ============================================================================
create table if not exists public.comercios (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  nombre varchar(80) not null unique,
  ubicacion varchar(150),
  descripcion text
);

-- Índices para comercios
create index if not exists idx_comercios_nombre on public.comercios (lower(nombre));

-- RLS y Políticas para comercios
alter table public.comercios enable row level security;

create policy "Permitir lectura anonima de comercios"
  on public.comercios for select to anon using (true);

create policy "Permitir insercion anonima de comercios"
  on public.comercios for insert to anon with check (true);

create policy "Permitir actualizacion anonima de comercios"
  on public.comercios for update to anon using (true);

create policy "Permitir eliminacion anonima de comercios"
  on public.comercios for delete to anon using (true);


-- ============================================================================
-- 3. Habilitar replicación Realtime para ambas tablas
-- ============================================================================
alter publication supabase_realtime add table public.precios;
alter publication supabase_realtime add table public.comercios;

-- Datos iniciales recomendados
insert into public.comercios (nombre, ubicacion, descripcion)
values
