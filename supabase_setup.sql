-- ============================================================================
-- 4. Hogares Compartidos (Grupos Privados con Código de Invitación)
-- ============================================================================
create table if not exists public.hogares (
  id uuid default gen_random_uuid() primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  nombre varchar(80) not null,
  codigo_invitacion varchar(16) not null unique,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade
);

create table if not exists public.hogar_miembros (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  hogar_id uuid not null references public.hogares(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  display_name varchar(80),
  rol varchar(20) not null default 'member' check (rol in ('owner', 'member')),
  unique (hogar_id, user_id)
);

create index if not exists idx_hogar_miembros_user on public.hogar_miembros (user_id);
create index if not exists idx_hogar_miembros_hogar on public.hogar_miembros (hogar_id);

-- Función helper SECURITY DEFINER para validar membresía sin recursión RLS
create or replace function public.es_miembro_hogar(p_hogar_id uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.hogar_miembros
    where hogar_id = p_hogar_id and user_id = auth.uid()
  );
$$;

alter table public.hogares enable row level security;
alter table public.hogar_miembros enable row level security;

drop policy if exists "Lectura de hogares propios" on public.hogares;
drop policy if exists "Creacion de hogar autenticado" on public.hogares;
drop policy if exists "Edicion de hogar por creador" on public.hogares;
drop policy if exists "Eliminacion de hogar por creador" on public.hogares;

create policy "Lectura de hogares propios"
  on public.hogares for select
  to authenticated
  using (created_by = auth.uid() or public.es_miembro_hogar(id));

create policy "Creacion de hogar autenticado"
  on public.hogares for insert
  to authenticated
  with check (auth.uid() = created_by and length(nombre) between 2 and 80);

create policy "Edicion de hogar por creador"
  on public.hogares for update
  to authenticated
  using (auth.uid() = created_by)
  with check (auth.uid() = created_by);

create policy "Eliminacion de hogar por creador"
  on public.hogares for delete
  to authenticated
  using (auth.uid() = created_by);

drop policy if exists "Lectura de miembros del hogar" on public.hogar_miembros;
drop policy if exists "Insercion de miembro propio" on public.hogar_miembros;
drop policy if exists "Salida o expulsion de miembro" on public.hogar_miembros;

create policy "Lectura de miembros del hogar"
  on public.hogar_miembros for select
  to authenticated
  using (user_id = auth.uid() or public.es_miembro_hogar(hogar_id));

create policy "Insercion de miembro propio"
  on public.hogar_miembros for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Salida o expulsion de miembro"
  on public.hogar_miembros for delete
  to authenticated
  using (
    user_id = auth.uid() or
    exists (select 1 from public.hogares h where h.id = hogar_id and h.created_by = auth.uid())
  );


