-- ============================================================================
-- 7. Funciones RPC Seguras para Crear / Unirse / Regenerar Código de Hogar
-- ============================================================================
create or replace function public.crear_hogar(p_nombre text, p_display_name text default null)
returns public.hogares
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_codigo text;
  v_hogar public.hogares;
begin
  if v_uid is null then
    raise exception 'Debes iniciar sesión para crear un hogar';
  end if;

  if length(trim(coalesce(p_nombre, ''))) < 2 then
    raise exception 'El nombre del hogar debe tener al menos 2 caracteres';
  end if;

  delete from public.hogar_miembros where user_id = v_uid;

  v_codigo := 'CH-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));

  insert into public.hogares (nombre, codigo_invitacion, created_by)
  values (trim(p_nombre), v_codigo, v_uid)
  returning * into v_hogar;

  insert into public.hogar_miembros (hogar_id, user_id, display_name, rol)
  values (v_hogar.id, v_uid, nullif(trim(coalesce(p_display_name, '')), ''), 'owner');

  update public.chango_items set hogar_id = v_hogar.id where user_id = v_uid and hogar_id is null;
  update public.stock_casa set hogar_id = v_hogar.id where user_id = v_uid and hogar_id is null;

  return v_hogar;
end;
$$;

create or replace function public.unirse_a_hogar(p_codigo text, p_display_name text default null)
returns public.hogares
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_hogar public.hogares;
begin
  if v_uid is null then
    raise exception 'Debes iniciar sesión para unirte a un hogar';
  end if;

  select * into v_hogar
  from public.hogares
  where upper(codigo_invitacion) = upper(trim(coalesce(p_codigo, '')))
  limit 1;

  if v_hogar.id is null then
    raise exception 'Código de invitación inválido o expirado';
  end if;

  delete from public.hogar_miembros where user_id = v_uid and hogar_id <> v_hogar.id;

  insert into public.hogar_miembros (hogar_id, user_id, display_name, rol)
  values (v_hogar.id, v_uid, nullif(trim(coalesce(p_display_name, '')), ''), 'member')
  on conflict (hogar_id, user_id) do update
    set display_name = coalesce(excluded.display_name, public.hogar_miembros.display_name);

  return v_hogar;
end;
$$;

create or replace function public.regenerar_codigo_hogar(p_hogar_id uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_nuevo text;
begin
  if v_uid is null then
    raise exception 'No autenticado';
  end if;

  v_nuevo := 'CH-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 5));

  update public.hogares
  set codigo_invitacion = v_nuevo
  where id = p_hogar_id and created_by = v_uid;

  if not found then
    raise exception 'Solo el creador del hogar puede regenerar el código';
  end if;

  return v_nuevo;
end;
$$;


